#!/usr/bin/env python3
"""Generates pdn_aprs_deviceid.c and mice_codes.c from the aprs-deviceid database.

  python3 tools/gen_deviceid.py path/to/aprs-deviceid [output.c]
  python3 tools/gen_deviceid.py --check path/to/aprs-deviceid

Reads tocalls.yaml from a checkout of https://github.com/aprsorg/aprs-deviceid
(not vendored here, and the build never fetches it: clone it yourself) and
writes two C files from it, recording the commit they were made from:

  src/pdn_aprs_deviceid.c  the optional table with the names (CC BY-SA 2.0
                           data, see THIRD-PARTY-NOTICES.md)
  src/mice_codes.c         the core's list of Mic-E device suffix codes, the
                           codes only, in the core's own compact form (MIT)

so updating the database updates both, and they cannot drift. With --check
nothing is written: the exit status says whether both files in src/ are what
the checkout gives. Needs PyYAML.

Non-ASCII characters in names are written as octal escapes of their UTF-8
bytes, so the C source stays plain ASCII for every compiler.
"""

import subprocess
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("gen_deviceid.py needs PyYAML: pip install pyyaml")


def c_string(value):
    if value is None:
        return "NULL"
    out = []
    for byte in str(value).encode("utf-8"):
        ch = chr(byte)
        if byte >= 0x80 or byte < 0x20:
            out.append("\\%03o" % byte)
        elif ch in '"\\':
            out.append("\\" + ch)
        elif ch == "?":
            # avoid trigraphs
            out.append("\\?")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def entries(rows, key):
    lines = []
    for row in rows:
        lines.append("    {%s, %s, %s, %s}," % (
            c_string(key(row)), c_string(row.get("vendor")), c_string(row.get("model")), c_string(row.get("class"))))
    return "\n".join(lines)


def code_entries(mice, legacy):
    """The core's codes: (type code, suffix bytes), sorted. A `/' Mic-E suffix
    is two bytes and goes with either of those type codes (type code 0); a
    legacy one is a single byte after > or ]. A legacy type code with no
    suffix is not a suffix code."""
    codes = set()
    for row in mice:
        suffix = row["suffix"]
        if len(suffix) != 2 or not suffix.isascii():
            sys.exit("Mic-E suffix %r is not two ASCII bytes" % suffix)
        codes.add((0, suffix))
    for row in legacy:
        prefix, suffix = row["prefix"], row.get("suffix") or ""
        if prefix not in (">", "]") or len(suffix) > 1 or not suffix.isascii():
            sys.exit("legacy Mic-E type %r %r is not > or ] and at most one ASCII byte" % (prefix, suffix))
        if suffix:
            codes.add((ord(prefix), suffix))
    return sorted(codes)


def c_char(ch):
    if ch == "\\":
        return "'\\\\'"
    if ch == "'":
        return "'\\''"
    if ch == "?":
        return "'\\?'"
    return "'" + ch + "'"


def core_text(commit, date, mice, legacy):
    codes = code_entries(mice, legacy)
    rows = []
    for tc, s in codes:
        tcs = "0" if tc == 0 else c_char(chr(tc))
        second = c_char(s[1]) if len(s) == 2 else "0"
        rows.append("    {%s, {%s, %s}}," % (tcs, c_char(s[0]), second))
    body = "\n".join(rows)
    return f"""/*
 * mice_codes.c - the Mic-E device suffix codes the decoder and encoder know.
 *
 * GENERATED by tools/gen_deviceid.py from the aprs-deviceid database,
 * https://github.com/aprsorg/aprs-deviceid commit {commit} ({date}).
 * Do not edit by hand; regenerate.
 *
 * What this is: the bytes a Mic-E comment can end in to name the sending
 * device, and nothing else (no vendor, model or class: those are in the
 * optional pdn_aprs_deviceid.c). The codes are those listed in the Mic-E
 * section of the APRS device identification database
 * (https://github.com/aprsorg/aprs-deviceid) and in APRS12c's Mic-E type code
 * text; being protocol facts, they are part of the MIT core. The list was
 * taken from the database at the commit above.
 *
 * Each row is the type code the suffix goes with and its bytes: 0 means the
 * suffix (two bytes) follows either ` or ', and > or ] mean the legacy
 * one-byte suffix after that type code (the second byte is 0). Sorted by type
 * code, then bytes. {len(codes)} codes.
 * SPDX-License-Identifier: MIT
 */
#include "internal.h"

static const struct {{
    char type_code;
    char s[2];
}} mic_e_codes[] = {{
{body}
}};

PDN_APRS__PRIVATE int pdn_aprs__mic_e_suffix_known(char type_code, const uint8_t *s, size_t n)
{{
    size_t i;
    char want = type_code == '`' || type_code == '\\'' ? 0 : type_code;
    if (n != 1 && n != 2)
        return 0;
    if (want != 0 && want != '>' && want != ']')
        return 0;
    for (i = 0; i < sizeof mic_e_codes / sizeof mic_e_codes[0]; i++)
        if (mic_e_codes[i].type_code == want && (uint8_t)mic_e_codes[i].s[0] == s[0] &&
            (n == 1 ? mic_e_codes[i].s[1] == 0 : mic_e_codes[i].s[1] != 0 && (uint8_t)mic_e_codes[i].s[1] == s[1]))
            return 1;
    return 0;
}}
"""


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    if len(args) < 1:
        sys.exit(__doc__)
    repo = Path(args[0])
    out = Path(args[1]) if len(args) > 1 else Path(__file__).resolve().parent.parent / "src" / "pdn_aprs_deviceid.c"
    core_out = out.parent / "mice_codes.c"
    data = yaml.safe_load((repo / "tocalls.yaml").read_text(encoding="utf-8"))
    commit = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True,
                            check=True).stdout.strip()
    date = subprocess.run(["git", "-C", str(repo), "log", "-1", "--format=%cs"], capture_output=True, text=True,
                          check=True).stdout.strip()

    tocalls = sorted(data["tocalls"], key=lambda r: str(r["tocall"]))
    mice = data["mice"]
    legacy = data["micelegacy"]

    text = f"""/*
 * pdn_aprs_deviceid.c - the APRS device identification table.
 *
 * GENERATED by tools/gen_deviceid.py from the aprs-deviceid database,
 * https://github.com/aprsorg/aprs-deviceid commit {commit} ({date}).
 * Do not edit by hand; regenerate.
 *
 * The data comes from the aprs-deviceid database, maintained by Heikki
 * Hannikainen, OH7LZB, and its contributors, and is licensed under CC BY-SA
 * 2.0 (https://creativecommons.org/licenses/by-sa/2.0/). See
 * THIRD-PARTY-NOTICES.md. This file is optional: pdn_aprs.c builds and works
 * without it, and then identifies no devices.
 */
#include "pdn_aprs.h"

static const pdn_aprs_device_entry tocalls[] = {{
{entries(tocalls, lambda r: r["tocall"])}
}};

static const pdn_aprs_device_entry mice[] = {{
{entries(mice, lambda r: r["suffix"])}
}};

static const pdn_aprs_device_entry mice_legacy[] = {{
{entries(legacy, lambda r: r["prefix"] + (r.get("suffix") or ""))}
}};

static const pdn_aprs_device_table table = {{
    tocalls, sizeof tocalls / sizeof tocalls[0],
    mice, sizeof mice / sizeof mice[0],
    mice_legacy, sizeof mice_legacy / sizeof mice_legacy[0],
}};

const pdn_aprs_device_table *pdn_aprs_devices(void)
{{
    return &table;
}}
"""
    core = core_text(commit, date, mice, legacy)
    if check:
        stale = [p.name for p, t in ((out, text), (core_out, core))
                 if not p.exists() or p.read_text(encoding="ascii") != t]
        if stale:
            sys.exit("out of date with %s: %s" % (commit, ", ".join(stale)))
        print("%s and %s are what %s gives" % (out.name, core_out.name, commit))
        return
    out.write_text(text, encoding="ascii")
    core_out.write_text(core, encoding="ascii")
    print(f"{core_out}: {len(code_entries(mice, legacy))} Mic-E suffix codes")
    print(f"{out}: {len(tocalls)} tocalls, {len(mice)} Mic-E suffixes, {len(legacy)} legacy Mic-E types, from {commit}")


if __name__ == "__main__":
    main()
